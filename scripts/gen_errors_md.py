#!/usr/bin/env python3
"""Render docs/ERRORS.md from src/brandcal/errors.py.

The meaning of each code is the attribute docstring under its ``ErrorCode`` member, read
with ``ast`` (the module is never imported). Exit codes come from ``EXIT_CODES``.

Usage: python scripts/gen_errors_md.py [--check] [--file PATH]
Without --check the file is (re)written. With --check it is left alone and the exit status
is 1, with a short message, if it differs from the generated text.
"""

from __future__ import annotations

import argparse
import ast
import sys
from collections.abc import Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "brandcal" / "errors.py"
TARGET = ROOT / "docs" / "ERRORS.md"
HEADER = (
    "# Error codes and exit codes\n"
    "\n"
    "<!-- generated by scripts/gen_errors_md.py, do not edit -->\n"
    "\n"
    "This file is generated by `scripts/gen_errors_md.py` from `src/brandcal/errors.py`. "
    "Do not edit it; change the docstring there and run `python scripts/gen_errors_md.py`.\n"
    "\n"
    "Exit 0 is success and exit 1 is never used deliberately (it means an unexpected crash).\n"
    "\n"
)


def _class(tree: ast.Module, name: str) -> ast.ClassDef:
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == name:
            return node
    raise ValueError(f"class {name} not found")


def _docstring(node: ast.stmt) -> str | None:
    if (
        isinstance(node, ast.Expr)
        and isinstance(node.value, ast.Constant)
        and isinstance(node.value.value, str)
    ):
        return " ".join(node.value.value.split())
    return None


def read_codes(source: str) -> list[tuple[int, str, str]]:
    """(exit code, error code, meaning) for every ErrorCode member, in source order."""
    tree = ast.parse(source)
    exits: dict[str, int] = {}
    for stmt in _class(tree, "ExitCode").body:
        if isinstance(stmt, ast.Assign) and isinstance(stmt.value, ast.Constant):
            exits[ast.unparse(stmt.targets[0])] = int(stmt.value.value)
    mapping: dict[str, int] = {}
    for node in tree.body:
        if (
            isinstance(node, ast.AnnAssign)
            and isinstance(node.target, ast.Name)
            and node.target.id == "EXIT_CODES"
            and isinstance(node.value, ast.Dict)
        ):
            for key, value in zip(node.value.keys, node.value.values, strict=True):
                if key is not None:
                    mapping[ast.unparse(key).split(".")[-1]] = exits[
                        ast.unparse(value).split(".")[-1]
                    ]
    body = _class(tree, "ErrorCode").body
    rows: list[tuple[int, str, str]] = []
    for prev, stmt in zip(body, body[1:], strict=False):
        meaning = _docstring(stmt)
        if meaning is not None and isinstance(prev, ast.Assign):
            name = ast.unparse(prev.targets[0])
            if name not in mapping:
                raise ValueError(f"{name} has no entry in EXIT_CODES")
            rows.append((mapping[name], name, meaning))
    return rows


def render(source: str) -> str:
    rows = sorted(read_codes(source), key=lambda r: (r[0], r[1]))
    lines = ["| Exit | Code | Meaning |", "|---|---|---|"]
    lines += [f"| {e} | `{c}` | {m.replace('|', chr(92) + '|')} |" for e, c, m in rows]
    return HEADER + "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/ERRORS.md.")
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    parser.add_argument("--file", type=Path, default=TARGET, help="file to write or check")
    args = parser.parse_args(argv)
    text = render(SOURCE.read_text(encoding="utf-8"))
    path: Path = args.file
    if args.check:
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            print(f"{path} is out of date: run python scripts/gen_errors_md.py")
            return 1
        return 0
    path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
