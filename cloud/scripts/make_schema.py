#!/usr/bin/env python3
"""Write cloud/schema.sql, the D1 schema, from src/brandcal/schema.sql (the reference).

D1 cannot register the SQL functions bc_now() and bc_row_hash(), so the triggers that call them
(content bump) and the status triggers are left out: the Worker and the Python core enforce those
rules in code, and the Worker checks every pushed change (D1_MIGRATION.md 4). Tables, CHECKs,
foreign keys and the append-only and role triggers are copied verbatim. A ``meta`` table adds the
write generation that makes every write optimistic, and the config. Run with ``--check`` to fail
if cloud/schema.sql is stale (tests/test_cloud_schema.py does this).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src" / "brandcal" / "schema.sql"
TARGET = ROOT / "cloud" / "schema.sql"
KEEP_TRIGGERS = (
    "events_no_update",
    "approvals_no_update",
    "events_no_delete",
    "approvals_no_delete",
    "approvals_roles",
)
# D1 refuses GLOB patterns over 50 bytes, so the window CHECK is split into its two halves. It
# accepts exactly the same values (a NULL window still passes, as before).
WINDOW_CHECK = "CHECK (window GLOB '????-??-??T??:??:??[+-]??:??/????-??-??T??:??:??[+-]??:??'),"
D1_WINDOW_CHECK = (
    "CHECK (length(window) = 51"
    " AND substr(window, 1, 25) GLOB '????-??-??T??:??:??[+-]??:??'"
    " AND substr(window, 26, 1) = '/'"
    " AND substr(window, 27) GLOB '????-??-??T??:??:??[+-]??:??'),"
)
META = """
-- D1 only: the write generation and the config (D1_MIGRATION.md 3). Every write batch starts
-- with UPDATE meta SET v = <seen + 1> WHERE k = 'gen'; the trigger aborts the whole batch when
-- another write got there first, so the caller reloads and tries again.
CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT NOT NULL);
INSERT OR IGNORE INTO meta (k, v) VALUES ('gen', '0');
CREATE TRIGGER IF NOT EXISTS meta_gen_guard
BEFORE UPDATE ON meta
WHEN OLD.k = 'gen' AND CAST(NEW.v AS INTEGER) <> CAST(OLD.v AS INTEGER) + 1
BEGIN
  SELECT RAISE(ABORT, 'CONFLICT: the calendar changed while this write was prepared');
END;
"""


def build() -> str:
    text = SOURCE.read_text(encoding="utf-8")
    assert WINDOW_CHECK in text
    text = text.replace(WINDOW_CHECK, D1_WINDOW_CHECK)
    tables = re.findall(r"CREATE TABLE IF NOT EXISTS .*?\n\);\n", text, re.DOTALL)
    lock = re.search(r"INSERT OR IGNORE INTO archive_lock VALUES \(1, 0\);\n", text)
    assert lock is not None
    triggers = {
        m[1]: m[0]
        for m in re.finditer(r"CREATE TRIGGER IF NOT EXISTS (\w+)\n.*?\nEND;\n", text, re.DOTALL)
    }
    out = [
        "-- GENERATED by cloud/scripts/make_schema.py from src/brandcal/schema.sql. Do not edit.\n",
        *tables,
        lock[0],
        *(triggers[name] for name in KEEP_TRIGGERS),
        META,
    ]
    return "\n".join(out)


if __name__ == "__main__":
    want = build()
    if "--check" in sys.argv:
        sys.exit(0 if TARGET.read_text(encoding="utf-8") == want else 1)
    TARGET.write_text(want, encoding="utf-8")
